const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { OperationsService } = require('../services/operations.service');
const OperationsStore = require('../stores/operations.store');
test('daily cash reporting uses exact payment dates, isolated staff scopes, pagination and real content issues', { skip: process.env.RUN_DB_TESTS !== '1' }, async t => {
  const mysql = require('mysql2/promise');
  const { databaseOptions } = require('../config/database-options');
  const options = databaseOptions();
  assert.ok(['127.0.0.1','localhost','::1'].includes(options.host));
  const database = 'tcv_ops_test_' + randomUUID().replaceAll('-','');
  const admin = await mysql.createConnection({ ...options, database: undefined });
  let db;
  t.after(async () => {
    if (db) await db.end();
    if (/^tcv_ops_test_[a-f0-9]{32}$/.test(database) && database !== options.database) await admin.query(`DROP DATABASE IF EXISTS \`${database}\``);
    await admin.end();
  });
  await admin.query(`CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
  db = require('../config/utc-pool')(mysql.createPool({ ...options, database, multipleStatements: true }));
  await db.query(fs.readFileSync(path.resolve(__dirname,'../../database/init_db.sql'),'utf8'));
  await db.query("INSERT INTO USERS(email,password_hash,full_name,role) VALUES ('owner@test.invalid','test','Owner','ADMIN'),('staff@test.invalid','test','Staff','STAFF')");
  const fixture = async ({ at='2024-02-28 17:00:00', created='2024-02-28 17:00:00', confirmed=1, creator=1, method='CASH', status='PAID', currency='VND', amount='50000.00', claimed=false }={}) => {
    const id=randomUUID();
    await db.query("INSERT INTO VISIT_SESSIONS(session_id,created_by,status,activated_at,expires_at,token_hash) VALUES(?,?,?,UTC_TIMESTAMP(),DATE_ADD(UTC_TIMESTAMP(),INTERVAL 1 DAY),?)",[id,creator,status==='PAID'?'ACTIVE':'PENDING',claimed?'a'.repeat(64):null]);
    await db.query('INSERT INTO PAYMENTS(session_id,payment_ref,payment_method,status,amount,currency,confirmed_by,paid_at,created_at) VALUES(?,?,?,?,?,?,?,?,?)',[id,'REF-'+id,method,status,amount,currency,confirmed,status==='PAID'?at:null,created]);
    return id;
  };
  const first = await fixture({ claimed: true });
  const second = await fixture({ confirmed: 2, creator: 1, amount:'12345.67',at:'2024-02-29 16:59:59',created:'2020-01-01 00:00:00' });
  await fixture({ currency:'USD',amount:'1.25' });
  await fixture({ at:'2024-02-28 16:59:59' });
  await fixture({ at:'2024-02-29 17:00:00' });
  await fixture({ method:'ONLINE' });
  await fixture({ confirmed:null });
  await fixture({ status:'PENDING',confirmed:null,creator:2 });
  await db.query("INSERT INTO POIS(name,category,latitude,longitude,status) VALUES('Needs audio','ANIMAL',10.788,106.707,'ACTIVE')");
  const api = new OperationsService(new OperationsStore(db));
  const owner = { userId:1,role:'ADMIN',status:'ACTIVE' }, staff = { userId:2,role:'STAFF',status:'ACTIVE' };
  const all = await api.get(owner,{date:'2024-02-29'});
  assert.deepEqual(all.counts,{total:4,paid:3,pending:1,failed:0,unclaimed:2});
  assert.deepEqual(all.totals,[{currency:'USD',amount:'1.25',count:1},{currency:'VND',amount:'62345.67',count:2}]);
  assert.equal(all.hourly.find(r=>r.amount==='12345.67').hour,23);
  assert.equal(all.content[0].name,'Needs audio');
  const mine=await api.get(staff,{date:'2024-02-29'});
  assert.equal(mine.scope,'MY_PAYMENTS'); assert.equal(mine.counts.paid,1); assert.equal(mine.counts.pending,1);
  assert.deepEqual(mine.staff,[]); assert.equal(mine.transactions.items.some(r=>r.sessionId===first),false);
  const queue=await api.get(owner,{date:'2024-02-29',status:'UNCLAIMED',q:second});
  assert.equal(queue.transactions.total,1); assert.equal(queue.transactions.items[0].sessionId,second);
  assert.equal(queue.counts.paid,3); // Totals describe the day, not the current table filter.
  assert.equal(JSON.stringify(queue).includes('token_hash'),false);
  assert.equal(JSON.stringify(queue).includes('a'.repeat(64)),false);
  assert.equal((await api.get(owner,{date:'2024-02-29',q:'%'})).transactions.total,0);
  for(let i=0;i<22;i++) await fixture({status:'PENDING',confirmed:null});
  const page=await api.get(owner,{date:'2024-02-29',status:'PENDING',page:'2'});
  assert.equal(page.transactions.total,23); assert.equal(page.transactions.items.length,3);
  const empty=await api.get(owner,{date:'2020-02-01'}); assert.equal(empty.counts.paid,0); assert.deepEqual(empty.totals,[]);
});
