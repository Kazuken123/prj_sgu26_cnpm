const {test}=require('node:test');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const fs=require('node:fs');
const path=require('node:path');
const {VisitorAnalyticsService}=require('../services/visitor-analytics.service');
const Store=require('../stores/visitor-analytics.store');
const SchemaStore=require('../stores/schema.store');
test('real SQL tracks presence, confirms dwell, prevents duplicate counts, closes exits and retains zero-visit POIs',{skip:process.env.RUN_DB_TESTS!=='1'},async t=>{
  const mysql=require('mysql2/promise'),options=require('../config/database-options').databaseOptions();
  assert.ok(['localhost','127.0.0.1','::1'].includes(options.host));
  const database='tcv_analytics_test_'+randomUUID().replaceAll('-','');
  const root=await mysql.createConnection({...options,database:undefined});let db;
  t.after(async()=>{if(db)await db.end();if(/^tcv_analytics_test_[a-f0-9]{32}$/.test(database)&&database!==options.database)await root.query(`DROP DATABASE IF EXISTS \`${database}\``);await root.end();});
  await root.query(`CREATE DATABASE \`${database}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
  db=require('../config/utc-pool')(mysql.createPool({...options,database,multipleStatements:true}));
  await db.query(fs.readFileSync(path.resolve(__dirname,'../../database/init_db.sql'),'utf8'));
  await new SchemaStore(db).migrateVisitorAnalytics();await new SchemaStore(db).migrateVisitorAnalytics();
  await db.query("INSERT INTO POIS(name,latitude,longitude,trigger_radius,status) VALUES ('Visited',10.787,106.707,30,'ACTIVE'),('Unvisited',10.788,106.708,30,'ACTIVE')");
  const service=new VisitorAnalyticsService(new Store(db)),actor={userId:1,role:'ADMIN',status:'ACTIVE'};
  const {token}=await service.create();const position={latitude:10.787,longitude:106.707,accuracy:5,sampleAgeMs:100};
  await service.touch(token,position);
  let report=await service.report(actor,{});assert.equal(report.activeNow,1);assert.equal(report.pois[0].visitors,0);
  await db.query('UPDATE ANALYTICS_SESSIONS SET last_received_at=DATE_SUB(UTC_TIMESTAMP(3),INTERVAL 30 SECOND)');
  await db.query('UPDATE ANALYTICS_POI_VISITS SET entered_at=DATE_SUB(UTC_TIMESTAMP(3),INTERVAL 30 SECOND)');
  await service.touch(token,position);await service.touch(token,position);
  report=await service.report(actor,{});assert.equal(report.visitors,1);assert.equal(report.entries,1);assert.equal(report.peak,1);
  assert.deepEqual(report.pois.map(p=>[p.name,p.visitors,p.visits]),[['Visited',1,1],['Unvisited',0,0]]);
  await service.touch(token,{exit:true});report=await service.report(actor,{});assert.equal(report.activeNow,0);assert.equal(report.visitors,1);
  await db.query('UPDATE ANALYTICS_SESSIONS SET last_received_at=DATE_SUB(UTC_TIMESTAMP(3),INTERVAL 30 SECOND)');
  await service.touch(token,position);report=await service.report(actor,{});assert.equal(report.activeNow,1);assert.equal(report.entries,2);assert.equal(report.visitors,1);
  await db.query('UPDATE ANALYTICS_PRESENCE SET ends_at=DATE_SUB(UTC_TIMESTAMP(3),INTERVAL 1 SECOND)');
  report=await service.report(actor,{});assert.equal(report.activeNow,0);
  const historical=await service.report(actor,{period:'year',date:'2024-06-15'});assert.equal(historical.hasCoverage,false);assert.ok(historical.buckets.every(b=>b.peak===null));
  const [columns]=await db.query('SHOW COLUMNS FROM ANALYTICS_SESSIONS');assert.ok(!columns.some(c=>/latitude|longitude|email|ip_address/.test(c.Field)));
  await assert.rejects(service.touch('f'.repeat(64),position),{code:'ANALYTICS_SESSION_EXPIRED'});
});
